//! The model-readable reference for `@gents/ux-sdk` and the custom properties
//! a plugin may use. Both files are generated from the desktop's frame by
//! `apps/gents-desktop/tests/ux-sdk-reference.test.ts`, which fails when they
//! stop matching its export namespace or its built stylesheet.

/// The whole generated reference: the index a model reads first, then one
/// `### NAME` section per SDK export and a final `### tokens` section.
pub const SDK_REFERENCE: &str = include_str!("sdk_reference.md");

/// The generator ends the index with a comment line that starts with this.
const SECTIONS_MARKER: &str = "\n<!-- Generated by ";

fn split_reference() -> (&'static str, &'static str) {
    let (index, rest) = SDK_REFERENCE
        .split_once(SECTIONS_MARKER)
        .expect("the generated SDK reference separates its index from its sections");
    (
        index,
        rest.split_once('\n').map_or("", |(_, sections)| sections),
    )
}

/// What a model needs before it picks blocks: the page skeleton, every export
/// on one line, and the tokens rule.
pub fn sdk_index() -> &'static str {
    split_reference().0.trim_end()
}

/// Every `(name, body)` of the reference, in the generator's order; the body
/// is the section without its `### NAME` heading.
pub fn sdk_sections() -> impl Iterator<Item = (&'static str, &'static str)> {
    split_reference().1.split("\n### ").filter_map(|section| {
        let (name, body) = section.trim_start_matches("### ").split_once('\n')?;
        Some((name.trim(), body.trim()))
    })
}

/// One export's props and example, or the `tokens` list.
pub fn sdk_section(name: &str) -> Option<&'static str> {
    sdk_sections()
        .find(|(candidate, _)| candidate.eq_ignore_ascii_case(name))
        .map(|(_, section)| section)
}

const FRAME_TOKENS: &str = include_str!("frame_tokens.txt");

/// The CSS custom properties the plugin frame defines for a plugin to use.
pub fn frame_tokens() -> impl Iterator<Item = &'static str> {
    FRAME_TOKENS.lines()
}
