// ---------------------------------------------------------------------------
// The owned-loop chokepoint.
//
// The claim `proofs/README.md` makes — and that `sanitize_history_for_provider`
// depends on — is that EVERY completion request in the system is born in the
// owned loop, which sanitizes loaded history at entry (`run_loop_stream`). The
// sanitize fence above is only worth anything if nothing bypasses it.
//
// Two source scans keep that honest. The first pins the set of files allowed to
// invoke a provider at all; a bypass would have to show up there. The second
// pins the set of files allowed to enter the owned loop, so a new completion
// path is visible in review rather than silent.
// ---------------------------------------------------------------------------

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .find(|path| path.join("crates/gents/proofs/lakefile.lean").exists())
        .expect("repository root should contain crates/gents/proofs/lakefile.lean")
        .to_path_buf()
}

/// Every non-test Rust source of the two crates the completion path lives
/// in.
///
/// `gents-loop` is walked as well as `gents`: the owned loop moved there,
/// and a scan that only looked here would report an empty seam and call it
/// clean, which is the one answer these tests must never give.
fn production_sources() -> Vec<(String, String)> {
    let root = repo_root();
    let mut out = Vec::new();
    let mut stack = vec![
        root.join("crates/gents/src"),
        root.join("crates/gents-loop/src"),
    ];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir)
            .unwrap_or_else(|err| panic!("failed to read {}: {err}", dir.display()))
        {
            let path = entry.expect("readable dir entry").path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            if path.extension().and_then(|ext| ext.to_str()) != Some("rs") {
                continue;
            }
            let relative = path
                .strip_prefix(&root)
                .expect("path under repo root")
                .to_string_lossy()
                .replace('\\', "/");
            // Test-only sources are not production call sites. Test code in
            // these crates lives in separate files rather than inline
            // `#[cfg(test)]` modules, so excluding by path is sufficient, and
            // unlike truncating at the first `#[cfg(test)]` it does not also
            // discard the file's real body (those markers sit at the top of
            // `loop_stream.rs` and `compaction.rs`, declaring `mod tests;`).
            // `gents` spells them `tests.rs`, `gents-loop` spells them
            // `<module>_tests.rs`; both are excluded, or the loop's own tests
            // would read as production call sites.
            let file_name = relative.rsplit('/').next().unwrap_or("");
            if relative.ends_with("/tests.rs")
                || relative.contains("/tests/")
                || file_name.ends_with("_tests.rs")
                || file_name.ends_with("_test.rs")
                || relative.contains("test_support")
                || relative.contains("lean_vocab_test")
            {
                continue;
            }
            let source = std::fs::read_to_string(&path)
                .unwrap_or_else(|err| panic!("failed to read {}: {err}", path.display()));
            out.push((relative, source));
        }
    }
    out.sort();
    out
}

fn files_containing(needles: &[&str]) -> BTreeSet<String> {
    production_sources()
        .into_iter()
        .filter(|(_, source)| needles.iter().any(|needle| source.contains(needle)))
        .map(|(path, _)| path)
        .collect()
}

/// No completion request may be issued outside the owned loop and the admission
/// wrapper it passes through. A new file here means a provider call that never
/// saw `sanitize_history_for_provider` — report it before fixing it.
#[test]
fn provider_invocations_are_confined_to_the_owned_loop_seam() {
    let expected = BTreeSet::from([
        // Builds the request and sends it: the one owned-loop seam.
        "crates/gents-loop/src/loop_stream.rs".to_string(),
        // Wraps a model to apply admission control; receives an
        // already-assembled request from the owned loop.
        "crates/gents/src/admission/client.rs".to_string(),
    ]);
    let found = files_containing(&[".completion_request(", ".completion(", ".stream("]);
    assert_eq!(
        found, expected,
        "provider invocation escaped the owned-loop seam; every completion request \
         must be born in run_loop_stream, which sanitizes loaded history at entry"
    );
}

/// The owned loop's entry points. Sanitization happens once, at the top of
/// `run_loop_stream`; every production completion path must come through here.
#[test]
fn owned_loop_entry_points_are_registered() {
    let expected = BTreeSet::from([
        // Text and typed helpers wrap `run_loop_stream`.
        "crates/gents-loop/src/loop_stream/one_shot.rs".to_string(),
        // Daemon request execution: the main path.
        "crates/gents/src/agent/daemon/inference.rs".to_string(),
        // Conversation title generation.
        "crates/gents/src/agent/daemon/title.rs".to_string(),
        // Compaction summarization.
        "crates/gents-loop/src/compaction.rs".to_string(),
        // One-shot CLI runs.
        "crates/gents/src/oneshot.rs".to_string(),
    ]);
    // Both spellings of each call. The loop's entry points are generic over
    // the session hook now, so a caller that has to name the hook writes
    // `run_loop_to_text::<M, DefraSessionHook>(...)` and a needle ending in
    // `(` would miss it. Missing an entry point here is the failure that
    // matters: it reads as "no new completion path", which is exactly what
    // this test exists to disprove.
    let found = files_containing(&[
        "run_loop_stream(",
        "run_loop_stream::<",
        "run_loop_to_text(",
        "run_loop_to_text::<",
        "run_loop_to_typed(",
        "run_loop_to_typed::<",
    ]);
    assert_eq!(
        found, expected,
        "the set of owned-loop entry points changed; a new completion path must be \
         reviewed against the sanitize-at-entry chokepoint"
    );
}

// ---------------------------------------------------------------------------
// The public constructor below starts with no available skills. This checks
// reminder lookup against that empty catalog only. Context whitelist selection,
// owner/enabled filtering, and reminders for selected available skills need the
// runtime loader migration; request-selected IDs are not the context whitelist.
