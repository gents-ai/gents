//! Conformance fence for the provider-input sanitizer.
//!
//! This fence used to be *social*: a human read `Proofs/PromptAssembly` and
//! hand-wrote assertions against a test-local pairing oracle. Nothing tied the
//! Rust sanitizer to the function the Lean theorems quantify over, so a change
//! to either side could break the correspondence without failing a test. That
//! is not hypothetical — `loop_stream.rs::repair_provider_input` records a bug
//! of exactly this shape, where "the fence described a transform that did not
//! exist".
//!
//! It is now mechanical. Every sanitize expectation below is generated by
//! running the Lean model (`PromptAssembly.Provider.sanitizeForProviderGlobal`)
//! and consumed here verbatim; see
//! `Proofs/Conformance/ContractCases/PromptAssembly.lean`.
//!
//! **Which sanitizer is fenced.** The emitted expectations are the
//! global-resolution proof model. Production implements the per-turn
//! algorithm (`history.rs::resolved_keys_per_turn` mirrors
//! `PromptAssembly.sanitizeTurn`); the two coincide exactly on the emitted
//! witnesses because every witness satisfies `UniqueCallIds` (checked in Lean
//! by `witnessesHaveUniqueCallIds`, aligned by `sanitizeTurn_eq_sanitizeGlobal`).
//! That witness alignment is all this fence claims: content-bearing per-turn
//! soundness and repeated-occurrence transfer remain explicit follow-up (see
//! proofs/README.md), so nothing here asserts a per-turn content guarantee —
//! the global model is a conditional proof oracle, not a second production
//! algorithm.
//!
//! **There is deliberately no provider-validity oracle in this file.** Validity
//! of each expected output is the Lean theorem
//! `Provider.sanitizeForProviderGlobal_sound`. Production that reproduces the
//! emitted output exactly inherits it. Re-deriving pairing rules in Rust would
//! just reintroduce the social fence this replaces.

